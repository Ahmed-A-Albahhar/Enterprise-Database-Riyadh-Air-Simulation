
SQL Tables creation
-- Create the AIRPLANE table
CREATE TABLE AIRPLANE (
  AIRPLANE_ID VARCHAR(10) NOT NULL PRIMARY KEY,
  MODEL_NUMBER VARCHAR(50) NOT NULL,
  CAPACITY INT NOT NULL
);

-- Create the PILOT table
CREATE TABLE PILOT (
  PILOT_ID VARCHAR(10) NOT NULL PRIMARY KEY,
  PFNAME VARCHAR(50) NOT NULL,
  PLNAME VARCHAR(50) NOT NULL,
  CONTACT_NUMBER VARCHAR(20) NOT NULL,
  PILOT_LICENSE VARCHAR(50) NOT NULL
);

-- Create the FLIGHT table
CREATE TABLE FLIGHT (
  FLIGHT_ID VARCHAR(10) NOT NULL PRIMARY KEY,
  FLIGHT_FARE DECIMAL(10,2) NOT NULL,
  DESTINATION VARCHAR(50) NOT NULL,
  DEPARTURE_FROM VARCHAR(50) NOT NULL,
  ARRIVAL_DATE DATE NOT NULL,
  DEPARTURE_DATE DATE NOT NULL,
  PILOT_ID VARCHAR(10) NOT NULL,
  FOREIGN KEY (PILOT_ID) REFERENCES PILOT(PILOT_ID)
);

-- Create the RESERVATION table
CREATE TABLE RESERVATION (
  RESERVATION_ID VARCHAR(10) NOT NULL PRIMARY KEY,
  DATE_OF_DEPARTURE DATE NOT NULL,
  DATE_OF_ARRIVAL DATE NOT NULL,
  LUGGAGE_ALLOWANCE INT NOT NULL,
  FLIGHT_ID VARCHAR(10) NOT NULL,
  FOREIGN KEY (FLIGHT_ID) REFERENCES FLIGHT(FLIGHT_ID)
);

-- Create the TICKET table
CREATE TABLE TICKET (
  TICKET_ID VARCHAR(10) NOT NULL PRIMARY KEY,
  RESERVATION_ID VARCHAR(10) NOT NULL,
  FARE DECIMAL(10,2) NOT NULL,
  MEAL VARCHAR(30) NOT NULL,
  FOREIGN KEY (RESERVATION_ID) REFERENCES RESERVATION(RESERVATION_ID)
);

-- Create the PASSENGER table
CREATE TABLE PASSENGER (
  PASSENGER_ID VARCHAR(10) NOT NULL PRIMARY KEY,
  FNAME VARCHAR(50) NOT NULL,
  LNAME VARCHAR(50) NOT NULL,
  EMAIL VARCHAR(100) NOT NULL UNIQUE,
  PHONE_NUM VARCHAR(20) NOT NULL,
  NATIONALITY VARCHAR(50) NOT NULL,
  DOB DATE NOT NULL,
  GENDER VARCHAR(6) NOT NULL,
  RESERVATION_ID VARCHAR(10) NOT NULL,
  FOREIGN KEY (RESERVATION_ID) REFERENCES RESERVATION(RESERVATION_ID)
);

-- Create the CABIN_TYPE table
CREATE TABLE CABIN_TYPE (
  CABIN_TYPE VARCHAR(20) NOT NULL,
  CABIN_FARE DECIMAL(10,2) NOT NULL,
  AIRPLANE_ID VARCHAR(10) NOT NULL,
  PRIMARY KEY (CABIN_TYPE, AIRPLANE_ID),
  FOREIGN KEY (AIRPLANE_ID) REFERENCES AIRPLANE(AIRPLANE_ID)
);

CREATE TABLE SEAT (
  SEAT_ID VARCHAR(10) NOT NULL PRIMARY KEY,
  CABIN_TYPE VARCHAR(20) NOT NULL,
  AIRPLANE_ID VARCHAR(10) NOT NULL,
  FLIGHT_ID VARCHAR(10) NOT NULL,
  FOREIGN KEY (CABIN_TYPE, AIRPLANE_ID) REFERENCES CABIN_TYPE(CABIN_TYPE, AIRPLANE_ID),
  FOREIGN KEY (FLIGHT_ID) REFERENCES FLIGHT(FLIGHT_ID)
);

