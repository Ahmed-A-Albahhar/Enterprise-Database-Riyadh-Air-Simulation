10 Example Queries
1.	List full details of all flights departing from Riyadh on December 12th, 2023.
SELECT * FROM FLIGHT
WHERE DEPARTURE_FROM = 'Riyadh' AND DEPARTURE_DATE = '2023-12-15';
2.	Find the total number of passengers traveling on flights departing on December 10th, 2023.
SELECT COUNT(*)
FROM PASSENGER
INNER JOIN RESERVATION ON PASSENGER.RESERVATION_ID = RESERVATION.RESERVATION_ID
INNER JOIN FLIGHT ON RESERVATION.FLIGHT_ID = FLIGHT.FLIGHT_ID
WHERE DEPARTURE_DATE = '2023-12-10';
3.	List all the flights operated by pilot Ahmed Ali.
SELECT * FROM FLIGHT
WHERE PILOT_ID = 'PILOT01';
4.	Find the average luggage allowance for flights departing from Jeddah in December 2023.
SELECT AVG(LUGGAGE_ALLOWANCE)
FROM RESERVATION
INNER JOIN FLIGHT ON RESERVATION.FLIGHT_ID = FLIGHT.FLIGHT_ID
WHERE DEPARTURE_FROM = 'Jeddah' AND DEPARTURE_DATE BETWEEN '2023-12-01' AND '2023-12-31';
5.	List all passengers traveling on flights departing on December 15th, 2023, along with their flight details and email addresses.
SELECT PASSENGER.FNAME, PASSENGER.LNAME, PASSENGER.EMAIL, FLIGHT.FLIGHT_ID, FLIGHT.DESTINATION, FLIGHT.DEPARTURE_DATE
FROM PASSENGER
INNER JOIN RESERVATION ON PASSENGER.RESERVATION_ID = RESERVATION.RESERVATION_ID
INNER JOIN FLIGHT ON RESERVATION.FLIGHT_ID = FLIGHT.FLIGHT_ID
WHERE DEPARTURE_DATE = '2023-12-15';
6.	Find the total revenue generated from ticket sales for flights departing on December 10th, 2023.
SELECT SUM(FARE)
FROM TICKET
INNER JOIN RESERVATION ON TICKET.RESERVATION_ID = RESERVATION.RESERVATION_ID
INNER JOIN FLIGHT ON RESERVATION.FLIGHT_ID = FLIGHT.FLIGHT_ID
WHERE DEPARTURE_DATE = '2023-12-10';
7.	List all airplanes with a capacity of more than 200 passengers.
SELECT * FROM AIRPLANE
WHERE CAPACITY > 200;
8.	Find the most frequent cabin type used in all airplanes.
SELECT CABIN_TYPE, COUNT(*) AS frequency
FROM SEAT
GROUP BY CABIN_TYPE
ORDER BY frequency DESC
LIMIT 1;
9.	List all pilots who are flying to Dubai in December 2023.
SELECT PILOT.PFNAME, PILOT.PLNAME, FLIGHT.DESTINATION
FROM PILOT
INNER JOIN FLIGHT ON PILOT.PILOT_ID = FLIGHT.PILOT_ID
WHERE DESTINATION = 'Dubai' AND DEPARTURE_DATE BETWEEN '2023-12-01' AND '2023-12-31';
10.	Find the average flight fare for flights departing from Riyadh to Dammam in December 2023.
SELECT AVG(FLIGHT_FARE)
FROM FLIGHT
WHERE DEPARTURE_FROM = 'Riyadh' AND DESTINATION = 'Damam' AND DEPARTURE_DATE BETWEEN '2023-12-01' AND '2023-12-31';
